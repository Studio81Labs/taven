async function monitorRequestWorkspace(): Promise<{
  modes: string[];
  childSecurity: string[];
  sandboxIsolation: string[];
}> {
  const command = [
    "attempt=0;",
    'while [ "$attempt" -lt 4000 ]; do',
    "for request in /var/run/taven-orca/request-*; do",
    '[ -d "$request" ] || continue;',
    '[ -d "$request/output" ] && [ -d "$request/tmp" ] && [ -d "$request/tmp/data" ] && [ -d "$request/profiles" ] && [ -d "$request/profiles/settings" ] && [ -d "$request/profiles/filaments" ] || continue;',
    'modes=$(stat -c \'%u:%g:%a\' "$request" "$request/output" "$request/tmp" "$request/tmp/data" "$request/profiles" "$request/profiles/settings" "$request/profiles/filaments");',
    "for status in /proc/[0-9]*/status; do",
    '[ -r "$status" ] || continue;',
    "command=$(tr '\\000' ' ' < \"${status%/status}/cmdline\" 2>/dev/null || true);",
    'case "$command" in *"/opt/orca/AppRun"*)',
    'case "$command" in *"--unshare-pid"*"--unshare-ipc"*"--unshare-uts"*"--ro-bind"*"--tmpfs"*) ;; *) continue ;; esac;',
    'for child_status in "${status%/status}"/root/proc/[0-9]*/status; do',
    '[ -r "$child_status" ] || continue;',
    "child_uid=$(awk '/^Uid:/{print $2}' \"$child_status\");",
    '[ "$child_uid" = "10001" ] || continue;',
    'printf "%s\\n" "$modes";',
    'printf "%s\\n" "$child_uid";',
    'for name in CapInh CapPrm CapEff CapBnd CapAmb; do awk -v name="$name" \'$1 == name ":" { print $2 }\' "$child_status"; done;',
    "awk '/^NoNewPrivs:/{print $2}' \"$child_status\";",
    'printf "%s\\n" "mnt:isolated" "pid:isolated" "ipc:isolated" "uts:isolated";',
    "exit 0;",
    "done;; esac;",
    "done;",
    "done;",
    "attempt=$((attempt + 1));",
    "sleep 0.01;",
    "done; exit 1",
  ].join(" ");
  const result = await composeOutput([
    "exec",
    "-T",
    "orca-runner",
    "/bin/sh",
    "-ec",
    command,
  ]);
  const observation = result.split("\n").filter(Boolean);
  if (observation.length !== 18) {
    throw new Error(
      "The real Orca runner did not expose a complete unprivileged child",
    );
  }
  return {
    modes: observation.slice(0, 7),
    childSecurity: observation.slice(7, 14),
    sandboxIsolation: observation.slice(14),
  };
}

async function assertBrokerSecurity(): Promise<void> {
  const rendered = JSON.parse(
    await composeOutput(["config", "--format", "json"]),
  ) as {
    services: Record<string, { profiles?: string[]; volumes?: unknown[] }>;
  };
  for (const [service, definition] of Object.entries(rendered.services)) {
    if (definition.profiles?.includes("worker")) {
      expect(
        JSON.stringify(definition.volumes ?? []),
        `${service} volumes`,
      ).not.toContain("docker.sock");
    }
  }
  const services = ["slicer-worker", "orca-runner", "slicer-volume-init"];
  const expectedCapabilities = {
    "slicer-worker": [],
    "orca-runner": ["CAP_SETGID", "CAP_SETPCAP", "CAP_SETUID", "CAP_SYS_ADMIN"],
    "slicer-volume-init": ["CAP_CHOWN"],
  } as const;
  let runner: string | undefined;
  for (const service of services) {
    const container = await composeOutput(["ps", "-a", "-q", service]);
    expect(container, `${service} container`).not.toBe("");
    const inspection = JSON.parse(
      await execute("docker", [
        "inspect",
        container,
        "--format",
        "{{json .}}",
      ]).then(({ stdout }) => stdout),
    ) as {
      Config: { User: string };
      HostConfig: {
        CapAdd: string[] | null;
        CapDrop: string[] | null;
        NetworkMode: string;
        Privileged: boolean;
        ReadonlyRootfs: boolean;
      };
      Image: string;
      Mounts: { Destination: string; Source: string }[];
    };
    const caps = inspection.HostConfig.CapAdd ?? [];
    expect(inspection.HostConfig.CapDrop ?? []).toContain("ALL");
    expect([...caps].sort()).toEqual([...expectedCapabilities[service]].sort());
    expect(
      inspection.Mounts.some(
        ({ Destination, Source }) =>
          Destination.includes("docker.sock") || Source.includes("docker.sock"),
      ),
    ).toBe(false);
    if (service === "orca-runner") {
      runner = container;
      expect(inspection.HostConfig.Privileged).toBe(false);
      expect(inspection.HostConfig.NetworkMode).toBe("none");
      expect(inspection.HostConfig.ReadonlyRootfs).toBe(true);
      expect(inspection.Config.User).toBe("0:10001");
      expect(inspection.Image).toBe(
        await execute("docker", [
          "image",
          "inspect",
          runtimeLock.image.tag,
          "--format",
          "{{.Id}}",
        ]).then(({ stdout }) => stdout.trim()),
      );
    }
  }
  expect(runner).toBeDefined();
  expect(
    await composeOutput([
      "exec",
      "-T",
      "orca-runner",
      "stat",
      "-c",
      "%u:%g:%a",
      "/var/run/taven-orca",
    ]),
  ).toBe("10001:10001:770");
}

