async function runSequence(captureWorkspace: boolean) {
  const sourceKey = `models/${ids.source}/source`;
  await store.write(sourceKey, inputs.sourceBytes, "model/stl");
  const sourceInput = {
    source: {
      modelFileId: ids.source,
      format: "stl" as const,
      objectKey: sourceKey,
      contentSha256: inputs.sourceSha256,
    },
    inspectionRevision: "runtime-e2e-inspection-v1",
    inspectionConfigSha256: digest("runtime-e2e-inspection-config"),
    canonicalizerRevision: "runtime-e2e-canonicalizer-v1",
    canonicalizerConfigSha256: digest("runtime-e2e-canonicalizer-config"),
    operation: { mode: "inspect_source" as const },
  };
  const sourceJob = envelope("model_inspection", sourceInput, ids.referenceJob);
  const sourceResult = await submit(sourceJob);
  const sourceOutcome = success(sourceResult);
  expect(sourceResult.kind).toBe("model_inspection");
  expect(sourceOutcome.canonicalGeometry).toBeNull();
  expect(sourceOutcome.findings).toEqual([]);
  const bodyIds = sourceOutcome.bodies.map(({ bodyId }) => bodyId);
  expect(bodyIds).toHaveLength(1);
  const canonicalInput = {
    ...sourceInput,
    operation: {
      mode: "canonicalize_selection" as const,
      sourceInspectionFingerprintSha256: sourceJob.inputFingerprintSha256,
      bodyIds,
      selectionSha256: geometrySelectionSha256(bodyIds),
      confirmedUnitConversion: {
        sourceUnit: "millimeter" as const,
        targetUnit: "millimeter" as const,
        scaleFactorPpm: 1_000_000,
      },
      targetGeometry: {
        modelGeometryId: ids.geometry,
        canonicalObjectKey: `geometries/${ids.geometry}/canonical`,
      },
    },
  };
  const canonicalResult = await submit(
    envelope("model_inspection", canonicalInput, ids.candidateJob),
  );
  const canonicalOutcome = success(canonicalResult);
  if (!canonicalOutcome.canonicalGeometry) {
    throw new Error("Canonicalization did not return immutable geometry");
  }
  const geometry = {
    sourceModelFileId: ids.source,
    sourceContentSha256: inputs.sourceSha256,
    modelGeometryId: ids.geometry,
    canonicalObjectKey: canonicalOutcome.canonicalGeometry.canonicalObjectKey,
    geometrySha256: canonicalOutcome.canonicalGeometry.geometrySha256,
    bodyIds,
    selectionSha256: canonicalOutcome.canonicalGeometry.selectionSha256,
  };
  const referenceInput = {
    geometry,
    referenceProfile: {
      revisionId: ids.referenceProfile,
      contentSha256: inputs.referenceBundleSha256,
      slicerEngine: runtimeLock.engine.name,
      slicerVersion: runtimeLock.engine.version,
    },
    printConfig: {
      revisionId: ids.printConfig,
      contentSha256: inputs.printBundleSha256,
    },
    partsPerPlate: 1,
  };
  const referenceJob = envelope(
    "reference_slice",
    referenceInput,
    ids.referenceJob,
  );
  const workspaceMonitor = captureWorkspace
    ? monitorRequestWorkspace()
    : undefined;
  const referencePromise = submit(referenceJob);
  const referenceResult = await referencePromise;
  if (referenceResult.outcome.status !== "succeeded") {
    await workspaceMonitor?.catch(() => undefined);
    throw new Error(
      `Reference slice failed with ${referenceResult.outcome.code}: ${await runnerDiagnostics()}`,
    );
  }
  const workspaceObservation = await workspaceMonitor;
  const referenceOutcome = success(referenceResult);
  expect(referenceResult.engine.name).toBe(runtimeLock.engine.name);
  expect(referenceOutcome.artifact.objectKey).toBe(
    referenceArtifactObjectKey(referenceJob.inputFingerprintSha256),
  );
  await assertStoredArtifact(referenceOutcome.artifact, 512 * 1024 * 1024);
  const machineBase = {
    geometry,
    machineId: ids.machine,
    machineProfile: {
      revisionId: ids.machineProfile,
      contentSha256: inputs.machineBundleSha256,
      slicerEngine: runtimeLock.engine.name,
      slicerVersion: runtimeLock.engine.version,
      productionArtifactFormat: "gcode_3mf" as const,
    },
    machineCalibration: {
      revisionId: ids.calibration,
      contentSha256: inputs.calibrationBundleSha256,
    },
    printConfig: {
      revisionId: ids.printConfig,
      contentSha256: inputs.printBundleSha256,
    },
    arrangementRevision: {
      revisionId: ids.arrangement,
      contentSha256: digest("runtime-e2e-arrangement"),
    },
    partsPerPlate: 2,
  };
  const occupancySliceTargets = [2].map((partsPerPlate) => {
    const cacheIdentitySha256 = machineOccupancyCacheIdentitySha256(
      machineBase,
      partsPerPlate,
    );
    return {
      partsPerPlate,
      cacheIdentitySha256,
      analysisObjectKey: `slice-metrics/${cacheIdentitySha256}/result.json`,
    };
  });
  const candidateInput = {
    ...machineBase,
    quantity: 2,
    shipmentPlanId: ids.shipment,
    occupancySliceTargets,
  };
  const candidateResult = await submit(
    envelope("candidate_estimate", candidateInput, ids.candidateJob),
  );
  const candidateOutcome = success(candidateResult);
  expect(candidateOutcome.occupancySlices).toHaveLength(1);
  expect(await listKeys("gcode/")).toEqual([]);
  expect(await listKeys("slice-metrics/")).toEqual([
    occupancySliceTargets[0]!.analysisObjectKey,
  ]);
  await Promise.all(
    candidateOutcome.occupancySlices.map(({ artifact }) =>
      assertStoredArtifact(artifact, 64 * 1024),
    ),
  );
  const productionInput = {
    ...machineBase,
    quantity: 3,
    acceptedJobId: ids.productionJob,
    productionReservationId: ids.reservation,
  };
  const productionJob = envelope(
    "production_slice",
    productionInput,
    ids.productionJob,
  );
  const productionResult = await submit(productionJob);
  const productionOutcome = success(productionResult);
  expect(productionOutcome.metrics.plateCount).toBe(2);
  expect(productionOutcome.artifact.objectKey).toBe(
    productionArtifactObjectKey(ids.productionJob, "gcode_3mf"),
  );
  const productionArtifact = await assertStoredArtifact(
    productionOutcome.artifact,
    512 * 1024 * 1024,
  );
  validateProductionArtifact(
    productionArtifact,
    "gcode_3mf",
    2,
    runtimeLock.engine.version,
    512 * 1024 * 1024,
  );
  return {
    source: sourceOutcome,
    canonical: canonicalOutcome,
    reference: referenceOutcome,
    candidate: candidateOutcome,
    production: productionOutcome,
    normalizedProductionPackage: normalizedProductionPackage(
      productionArtifact,
      productionOutcome.metrics.plateCount,
    ),
    workspaceModes: workspaceObservation?.modes,
    childSecurity: workspaceObservation?.childSecurity,
    sandboxIsolation: workspaceObservation?.sandboxIsolation,
    outputKeys: [
      referenceOutcome.artifact.objectKey,
      ...occupancySliceTargets.map(
        ({ analysisObjectKey }) => analysisObjectKey,
      ),
      productionOutcome.artifact.objectKey,
    ],
  };
}

