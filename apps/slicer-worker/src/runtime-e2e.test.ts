function digest(value: string): string {
  return createHash("sha256").update(value, "utf8").digest("hex");
}

function bytes(value: unknown): Uint8Array {
  return new TextEncoder().encode(JSON.stringify(value));
}

function normalizedGcodeSha256(value: Uint8Array): string {
  const source = new TextDecoder("utf-8", { fatal: true }).decode(value);
  return sha256(
    new TextEncoder().encode(
      source.replace(
        /^(; generated by OrcaSlicer \S+ on )\d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}$/mu,
        "$1<timestamp>",
      ),
    ),
  );
}

function normalizedProductionPackage(bytes: Uint8Array, plateCount: number) {
  const entries = readBoundedZipEntries(bytes, {
    label: "Runtime G-code 3MF archive",
    invalidCode: "INVALID_GEOMETRY",
    maximumEntries: 256,
    maximumEntryBytes: 512 * 1024 * 1024,
    maximumTotalBytes: 512 * 1024 * 1024,
  });
  return {
    plates: Array.from({ length: plateCount }, (_, index) => {
      const name = `Metadata/plate_${index + 1}.gcode`;
      const gcode = entries.get(name)!;
      const declaredMd5 = new TextDecoder("utf-8", { fatal: true })
        .decode(entries.get(`${name}.md5`)!)
        .trim();
      return {
        name,
        normalizedGcodeSha256: normalizedGcodeSha256(gcode),
        md5Matches:
          declaredMd5 ===
          createHash("md5").update(gcode).digest("hex").toUpperCase(),
      };
    }),
  };
}

function bundle(...presets: readonly Record<string, unknown>[]): Uint8Array {
  return bytes({ bundleVersion: 1, presets });
}

function envelope(kind: SlicingJobKind, input: unknown, jobId: string) {
  const inputFingerprintSha256 = slicingInputFingerprint(kind, input);
  return {
    contractVersion: 2,
    kind,
    jobId,
    correlationId: jobId,
    inputFingerprintSha256,
    idempotencyKey: `slicer:v2:${kind}:${jobId}:${inputFingerprintSha256}`,
    attempt: 1,
    input,
  };
}

function success(result: SlicingResult) {
  if (result.outcome.status !== "succeeded") {
    throw new Error(
      `Expected ${result.kind} to succeed, received ${result.outcome.code}`,
    );
  }
  return result.outcome;
}

async function compose(arguments_: readonly string[]) {
  return execute("docker", [...composeFiles, ...arguments_], {
    cwd: repositoryRoot,
    env: composeEnvironment,
    maxBuffer: 16 * 1024 * 1024,
  });
}

async function composeOutput(arguments_: readonly string[]): Promise<string> {
  const { stdout } = await compose(arguments_);
  return stdout.trim();
}

async function submit(
  job: ReturnType<typeof envelope>,
): Promise<SlicingResult> {
  sequence += 1;
  const queued = await queue.add("runtime-e2e", job, {
    jobId: `runtime-e2e-${sequence}`,
    attempts: 1,
    removeOnComplete: true,
    removeOnFail: true,
  });
  try {
    return SlicingResultSchema.parse(
      await queued.waitUntilFinished(events, 5 * 60 * 1_000),
    );
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    const diagnostics = await composeOutput([
      "logs",
      "--tail",
      "80",
      "slicer-worker",
      "orca-runner",
    ]).catch(() => "container logs unavailable");
    throw new Error(
      `Slicing job ${job.jobId} failed: ${message}\n${diagnostics}`,
      { cause: error },
    );
  }
}

async function listKeys(prefix: string): Promise<string[]> {
  const response = await directS3.send(
    new ListObjectsV2Command({ Bucket: "taven", Prefix: prefix }),
  );
  return (response.Contents ?? [])
    .map(({ Key }) => Key)
    .filter((key): key is string => key !== undefined)
    .sort();
}

async function assertStoredArtifact(
  artifact: { objectKey: string; sha256: string },
  maximumBytes: number,
): Promise<Uint8Array> {
  const stored = await store.read(
    artifact.objectKey,
    maximumBytes,
    artifact.sha256,
  );
  expect(stored, `${artifact.objectKey} exists`).not.toBeNull();
  expect(stored!.sha256).toBe(artifact.sha256);
  return stored!.bytes;
}

async function writeSnapshot(contents: Uint8Array): Promise<string> {
  const contentSha256 = sha256(contents);
  await store.write(
    `slicer-revisions/${contentSha256}/settings.json`,
    contents,
    "application/json",
  );
  return contentSha256;
}

async function waitForObjectStore(): Promise<void> {
  const deadline = Date.now() + 30_000;
  while (Date.now() < deadline) {
    try {
      await directS3.send(new HeadBucketCommand({ Bucket: "taven" }));
      return;
    } catch {
      await new Promise((resolve) => setTimeout(resolve, 100));
    }
  }
  throw new Error("The integration object store did not become ready");
}

